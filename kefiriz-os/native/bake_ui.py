"""Build the embedded software-renderer art using Pillow and librsvg's rsvg-convert."""
import argparse
import io
import itertools
import shutil
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
UI = HERE.parent / "ui"
SVG = "http://www.w3.org/2000/svg"
ICONS = ["download", "library", "album", "controller", "settings", "power",
         "profiles", "software", "network", "back", "play"]


def runs(data):
    encoded = bytearray()
    for value, group in itertools.groupby(data):
        n = sum(1 for _ in group)
        while n:
            count = min(n, 255)
            encoded.extend((count, value))
            n -= count
    return encoded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rsvg", default=shutil.which("rsvg-convert") or "rsvg-convert")
    args = parser.parse_args()
    sprite = ET.parse(UI / "icons.svg").getroot()
    sources = {symbol.attrib["id"]: symbol for symbol in sprite}
    ET.register_namespace("", SVG)
    output = ["/* Generated by bake_ui.py from the KEFIRIZ SVGs and OFL-licensed Barlow fonts. */"]

    def array(name, values, ctype="unsigned char", columns=24):
        output.append(f"static const {ctype} {name}[] = {{")
        values = list(values)
        for i in range(0, len(values), columns):
            output.append(",".join(map(str, values[i:i+columns])) + ",")
        output.append("};")

    def render(data, width, height):
        result = subprocess.run([args.rsvg, "-w", str(width), "-h", str(height), "-f", "png"],
                                input=data, capture_output=True, check=True)
        return Image.open(io.BytesIO(result.stdout)).convert("RGBA")

    def symbol(name, width, height, color="#ffffff"):
        item = sources[name]
        root = ET.Element(f"{{{SVG}}}svg", {**sprite.attrib, "viewBox": item.attrib["viewBox"], "color": color})
        root.extend(list(item))
        return render(ET.tostring(root), width, height)

    def packed_rgb(name, rgb):
        rgb = rgb.convert("RGB")
        packed = bytearray()
        for color, group in itertools.groupby(rgb.getdata()):
            n = sum(1 for _ in group)
            while n:
                count = min(n, 255)
                packed.extend((count, *color))
                n -= count
        array(name + "_rle", packed)

    contour = render((UI / "contours.svg").read_bytes(), 1280, 720)
    fade = Image.linear_gradient("L")
    grad = Image.blend(fade.resize((1280,720)), fade.transpose(Image.Transpose.ROTATE_90).resize((1280,720)), .42)
    wordface = ImageFont.truetype(str(UI / "font/Barlow-SemiBold.ttf"), 25)
    for name, start, end, ink, rule in [
        ("dark", "#1c2021", "#2e3232", "#f3f1e9", "#353a39"),
        ("light", "#f6f4ec", "#e0e3de", "#2d3435", "#d5d8d1")
    ]:
        bg = Image.composite(Image.new("RGB", grad.size, end), Image.new("RGB", grad.size, start), grad).convert("RGBA")
        bg.alpha_composite(contour)
        bg.alpha_composite(symbol("mark", 35,31,ink), (69,55))
        d = ImageDraw.Draw(bg)
        x = 106
        for char in "KEFIRIZ":
            d.text((x,77), char, font=wordface, fill=ink, anchor="ls")
            x += wordface.getlength(char) + 3.0
        d.line((73,120,1207,120),fill=rule,width=1)
        d.line((73,638,1207,638),fill=rule,width=1)
        packed_rgb("bg_"+name, bg)

    packed_rgb("torrent", render((UI / "download-tile.svg").read_bytes(),242,242))
    masks = bytearray()
    for icon in ICONS:
        icon_image = symbol(icon, 40, 40)
        for r,g,b,a in icon_image.getdata():
            masks.append(a * min(r,g,b)//255)
    array("icon_masks", masks)

    question = Image.new("L",(68,96))
    large_face = ImageFont.truetype(str(UI / "font/Barlow-Regular.ttf"), 83)
    ImageDraw.Draw(question).text((34,47),"?",font=large_face,fill=255,anchor="mm")
    array("empty_mask", question.tobytes())
    codes = list(range(32,127)) + list(range(160,384)) + list(range(0x400,0x460))
    codes += [0x490,0x491,0x2013,0x2014,0x2018,0x2019,0x201c,0x201d,0x2022,0x2026]
    cyrillic = ImageFont.truetype(str(UI / "font/ptsans/PT_Sans-Web-Regular.ttf"), 40)
    array("font_codes", codes, "uint16_t")
    pixels, glyphs = bytearray(), []
    for suffix in ["Regular", "SemiBold"]:
        latin = ImageFont.truetype(str(UI / ("font/Barlow-"+suffix+".ttf")), 40)
        for code in codes:
            font = cyrillic if 0x400 <= code <= 0x491 else latin
            char = chr(code)
            x,y,right,bottom = font.getbbox(char, anchor="ls")
            w,h = right-x,bottom-y
            glyphs.append(f"{{{len(pixels)},{x},{y},{w},{h},{round(font.getlength(char)*16)}}}")
            if w and h:
                bmp = Image.new("L",(w,h)); ImageDraw.Draw(bmp).text((-x,-y),char,font=font,fill=255,anchor="ls")
                pixels.extend(bmp.tobytes())
    output.append(f"#define KZ_FONT_BYTES {len(pixels)}\n#define KZ_GLYPH_COUNT {len(codes)}")
    array("font_glyphs",glyphs,"KzGlyph",5)
    array("font_rle",runs(pixels))
    (HERE / "draw_art.inc").write_text("\n".join(output)+"\n",encoding="ascii")


if __name__ == "__main__":
    main()
